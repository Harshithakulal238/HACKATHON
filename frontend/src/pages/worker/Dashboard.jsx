import { useCallback, useEffect, useMemo, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import BrandHeader from '../../components/layout/BrandHeader.jsx'
import QRCodeImage from '../../components/qr/QRCodeImage.jsx'
import { useAuth } from '../../context/useAuth.js'
import {
  createVisitorTour,
  listTourCategories,
  listWorkerFloorplans,
  listWorkerTours,
} from '../../services/tourService.js'
import '../PrototypePages.css'

function WorkerDashboard() {
  const { accessToken, signOut, user } = useAuth()
  const navigate = useNavigate()
  const [categories, setCategories] = useState([])
  const [floorplans, setFloorplans] = useState([])
  const [sessions, setSessions] = useState([])
  const [selectedFloorplanId, setSelectedFloorplanId] = useState('')
  const [selectedInterests, setSelectedInterests] = useState([])
  const [availableMinutes, setAvailableMinutes] = useState(30)
  const [ticket, setTicket] = useState(null)
  const [error, setError] = useState('')
  const [busy, setBusy] = useState(false)

  const refresh = useCallback(async () => {
    const [categoryResult, floorplanResult, sessionResult] = await Promise.all([
      listTourCategories(accessToken),
      listWorkerFloorplans(accessToken),
      listWorkerTours(accessToken),
    ])
    setCategories(categoryResult.categories)
    setFloorplans(floorplanResult.floorplans)
    setSelectedFloorplanId((current) => {
      if (floorplanResult.floorplans.some((floorplan) => floorplan.id === current)) {
        return current
      }
      return floorplanResult.floorplans.length === 1
        ? floorplanResult.floorplans[0].id
        : ''
    })
    setSessions(sessionResult.sessions)
  }, [accessToken])

  useEffect(() => {
    refresh().catch((requestError) => setError(requestError.message))
  }, [refresh])

  const routeUrl = useMemo(() => {
    if (!ticket?.routeToken) return ''
    const url = new URL('/visitor/tour', window.location.origin)
    url.searchParams.set('token', ticket.routeToken)
    return url.toString()
  }, [ticket])

  function toggleInterest(id) {
    setSelectedInterests((current) =>
      current.includes(id)
        ? current.filter((value) => value !== id)
        : [...current, id],
    )
  }

  async function createTicket(event) {
    event.preventDefault()
    setError('')
    setTicket(null)
    setBusy(true)
    try {
      const result = await createVisitorTour(accessToken, {
        interests: selectedInterests,
        availableMinutes: Number(availableMinutes),
        floorplanId: selectedFloorplanId,
      })
      setTicket(result)
      await refresh()
    } catch (requestError) {
      setError(requestError.message)
    } finally {
      setBusy(false)
    }
  }

  function handleSignOut() {
    signOut()
    navigate('/worker/login', { replace: true })
  }

  return (
    <main className="workspace-page">
      <header className="workspace-header">
        <BrandHeader />
        <div className="workspace-account">
          <span>{user.fullName}</span>
          <button className="workspace-button-secondary" onClick={handleSignOut} type="button">Sign out</button>
        </div>
      </header>
      <section className="workspace-content">
        <h1>Prepare a visitor tour</h1>
        <p className="page-intro">
          Choose interests and available time. The route and ticket are generated by the museum API.
        </p>
        {error ? <p className="notice notice-error" role="alert">{error}</p> : null}
        <div className="workspace-grid workspace-grid-two">
          <section className="workspace-panel">
            <h2>Visitor preferences</h2>
            {categories.length === 0 ? (
              <p className="notice notice-warning">
                The curator needs to add interest categories before tickets can be created.
              </p>
            ) : floorplans.length === 0 ? (
              <p className="notice notice-warning">
                The curator needs to add a floorplan before tickets can be created.
              </p>
            ) : (
              <form className="workspace-form" onSubmit={createTicket}>
                <label>
                  Floorplan
                  <select
                    className="workspace-input"
                    onChange={(event) => setSelectedFloorplanId(event.target.value)}
                    required
                    value={selectedFloorplanId}
                  >
                    <option value="">Select a floorplan</option>
                    {floorplans.map((floorplan) => (
                      <option key={floorplan.id} value={floorplan.id}>
                        {floorplan.name}{floorplan.floorLabel ? ` — ${floorplan.floorLabel}` : ''}
                      </option>
                    ))}
                  </select>
                </label>
                <fieldset className="workspace-form">
                  <legend className="workspace-field-label">Choose interests</legend>
                  <div className="interest-options">
                    {categories.map((category) => (
                      <label className="interest-option" key={category.id}>
                        <input
                          checked={selectedInterests.includes(category.id)}
                          onChange={() => toggleInterest(category.id)}
                          type="checkbox"
                        />
                        {category.name}
                      </label>
                    ))}
                  </div>
                </fieldset>
                <label>
                  Available tour time (minutes)
                  <input
                    max="480"
                    min="5"
                    onChange={(event) => setAvailableMinutes(event.target.value)}
                    required
                    type="number"
                    value={availableMinutes}
                  />
                </label>
                <button
                  className="workspace-button"
                  disabled={busy || !selectedFloorplanId || selectedInterests.length === 0}
                  type="submit"
                >
                  {busy ? 'Generating route…' : 'Generate route and ticket'}
                </button>
              </form>
            )}
          </section>

          <section className="workspace-panel">
            <h2>Recent sessions</h2>
            {sessions.length === 0 ? <p className="muted-copy">No visitor sessions created by this worker.</p> : (
              <ul className="workspace-list">
                {sessions.map((session) => (
                  <li className="workspace-list-item" key={session.id}>
                    <div>
                      <h3>{session.status}</h3>
                      <p>{session.allocatedMinutes} minutes · {new Date(session.createdAt).toLocaleString()}</p>
                    </div>
                  </li>
                ))}
              </ul>
            )}
          </section>
        </div>

        {ticket ? (
          <section className="workspace-panel" style={{ marginTop: 18 }}>
            <h2>Visitor ticket</h2>
            <p className="muted-copy">
              Session ID: {ticket.session.id} · {ticket.session.allocatedMinutes} minutes · Ready to start
            </p>
            <p><strong>Interests:</strong> {ticket.session.interests.map((interest) => interest.name).join(', ')}</p>
            <ol>
              {ticket.route.stops.map((stop, index) => (
                <li key={`${stop.nodeId}-${index}`}>
                  {stop.stopType === 'exit' ? 'Exit' : stop.name}
                  {stop.visitMinutes ? ` · ${stop.visitMinutes} min` : ''}
                </li>
              ))}
            </ol>
            <QRCodeImage value={routeUrl} label="Visitor route QR code" />
            <p className="muted-copy">The QR contains only a random session token, not the route or visitor details.</p>
          </section>
        ) : null}
      </section>
    </main>
  )
}

export default WorkerDashboard
